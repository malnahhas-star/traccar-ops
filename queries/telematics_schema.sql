-- 7.1 Live snapshot per vehicle — feeds LiveTrackingPayloadDto / map screen.
--     30-day fixtime fence keeps chunk pruning effective; a vehicle silent
--     longer shows NULL live fields (it is offline anyway).
CREATE OR REPLACE VIEW v_live_vehicles AS
SELECT
    v.id                AS vehicle_id,
    v.vehicle_name,
    v.plate_number,
    v.imei,
    d.id                AS tc_device_id,
    d.status            AS traccar_status,        -- online|offline|unknown
    d.lastupdate AT TIME ZONE 'UTC'      AS last_update,
    p.fixtime    AT TIME ZONE 'UTC'      AS position_time,
    p.latitude          AS lat,
    p.longitude         AS lng,
    round((p.speed * 1.852)::numeric, 1) AS speed_kmh,   -- knots → km/h
    p.course            AS heading,
    p.address,
    a.attrs ->> 'ignition'                    AS ignition,
    a.attrs ->> 'motion'                      AS motion,
    (a.attrs ->> 'fuel')::numeric             AS fuel_level,
    (a.attrs ->> 'sat')::int                  AS satellites,
    (a.attrs ->> 'rssi')::int                 AS gsm_signal,
    (a.attrs ->> 'power')::numeric            AS battery_external_v,
    (a.attrs ->> 'batteryLevel')::numeric     AS battery_internal_percent,
    (a.attrs ->> 'odometer')::numeric / 1000  AS odometer_km,
    a.attrs                                   AS raw_attributes
FROM telematics.vehicles v
JOIN tc_devices d ON d.uniqueid = v.imei
LEFT JOIN LATERAL (
    SELECT * FROM tc_positions p
    WHERE p.deviceid = d.id
      AND p.fixtime > (now() - interval '30 days')::timestamp
    ORDER BY p.fixtime DESC
    LIMIT 1
) p ON true
LEFT JOIN LATERAL (
    SELECT replace(p.attributes, '\u0000', '')::jsonb AS attrs OFFSET 0
) a ON p.id IS NOT NULL
WHERE v.deleted_at IS NULL;

-- 7.2 Playback / tracking-console route (TrackingRoutePoint[]).
CREATE OR REPLACE FUNCTION fn_playback(
    p_vehicle_id integer,
    p_from       timestamptz,
    p_to         timestamptz)
RETURNS TABLE (
    ts          timestamptz,
    lat         double precision,
    lng         double precision,
    speed_kmh   numeric,
    heading     double precision,
    ignition    text,
    fuel        numeric,
    temperature numeric
)
LANGUAGE sql STABLE AS $$
    SELECT
        p.fixtime AT TIME ZONE 'UTC',
        p.latitude,
        p.longitude,
        round((p.speed * 1.852)::numeric, 1),
        p.course,
        a.attrs ->> 'ignition',
        (a.attrs ->> 'fuel')::numeric,
        (a.attrs ->> 'temp1')::numeric
    FROM telematics.vehicles v
    JOIN tc_devices d ON d.uniqueid = v.imei
    JOIN tc_positions p ON p.deviceid = d.id
    CROSS JOIN LATERAL (
        SELECT replace(p.attributes, '\u0000', '')::jsonb AS attrs OFFSET 0
    ) a
    WHERE v.id = p_vehicle_id
      AND p.fixtime >= (p_from AT TIME ZONE 'UTC')::timestamp
      AND p.fixtime <  (p_to   AT TIME ZONE 'UTC')::timestamp
    ORDER BY p.fixtime
$$;

-- 7.3 Event feed (notifications source / harsh & sos views).
CREATE OR REPLACE VIEW v_vehicle_events AS
SELECT
    e.id          AS tc_event_id,
    v.id          AS vehicle_id,
    v.company_id,
    e.type,
    e.eventtime AT TIME ZONE 'UTC' AS at,
    e.positionid,
    e.attributes
FROM tc_events e
JOIN tc_devices d ON d.id = e.deviceid
JOIN telematics.vehicles v ON v.imei = d.uniqueid;

CREATE OR REPLACE VIEW v_harsh_events AS
SELECT * FROM v_vehicle_events
WHERE type = 'alarm'
  AND attributes ~ '(hardBraking|hardAcceleration|hardCornering)';

CREATE OR REPLACE VIEW v_sos_events AS
SELECT ev.*, ack.acked_by, ack.acked_at, ack.resolution
FROM v_vehicle_events ev
LEFT JOIN telematics.sos_acknowledgements ack ON ack.tc_event_id = ev.tc_event_id
WHERE ev.type = 'alarm' AND ev.attributes ~ '"alarm"\s*:\s*"sos"';

-- 7.4 Daily activity per vehicle from the rollup layer (dashboards/KPIs) —
--     answers in milliseconds, no hypertable scan.
CREATE OR REPLACE VIEW v_vehicle_daily_stats AS
SELECT
    v.id  AS vehicle_id,
    v.company_id,
    s.day,
    s.msg_count,
    s.moving_msgs,
    s.stopped_msgs,
    s.idle_msgs,
    s.first_fixtime AT TIME ZONE 'UTC' AS first_message,
    s.last_fixtime  AT TIME ZONE 'UTC' AS last_message,
    round((s.interval_sum        / NULLIF(s.interval_cnt, 0))::numeric, 1)        AS avg_interval_sec,
    round((s.moving_interval_sum / NULLIF(s.moving_interval_cnt, 0))::numeric, 1) AS moving_avg_interval_sec
FROM device_daily_stats s
JOIN tc_devices d ON d.id = s.deviceid
JOIN telematics.vehicles v ON v.imei = d.uniqueid;


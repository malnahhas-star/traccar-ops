-- ============================================================================
-- TELEMATICS SCHEMA — DDL DRAFT v1 (2026-07-18)
-- Fleet app backend schema living INSIDE the traccar database, isolated in
-- schema "telematics". App-owned data = real tables. Anything derivable from
-- Traccar's live tables (tc_positions / tc_events / tc_devices /
-- device_daily_stats) = views + functions, so there is ONE source of truth
-- and no second ingest pipeline.
--
-- Design rules
--  * The bridge to Traccar is telematics.vehicles.imei = tc_devices.uniqueid;
--    tc_device_id is cached for fast joins. NO hard FK into tc_* tables:
--    Traccar's own migrations/registerUnknown must stay free to manage them.
--  * App tables use timestamptz (app speaks ISO-8601 UTC). Traccar columns
--    are timestamp WITHOUT tz (UTC by convention) — the views cast at the edge.
--  * ids: GENERATED BY DEFAULT AS IDENTITY (bigint for high-volume tables).
--  * JSON-shaped payloads (permissions, polygon coords, sensor maps) = jsonb.
--  * Everything owned by role "telematics": full rights here, SELECT-only on
--    the Traccar tables it reads. Never write tc_* from the app.
-- ============================================================================

